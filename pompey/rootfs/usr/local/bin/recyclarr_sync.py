def env(name: str, default: str = "") -> str:
    return os.environ.get(name, default).strip()


def log(msg: str, level: str = "INFO") -> None:
    stamp = time.strftime("%H:%M:%S")
    print(f"[{stamp}] {level}: [recyclarr_sync.py] {msg}", flush=True)


def secrets_path() -> str:
    return env("POMPEY_SECRETS", "/data/pompey/secrets.json")


def app_data() -> str:
    return env("POMPEY_RECYCLARR_DATA") or os.path.join(
        env("POMPEY_DATA", "/data/pompey"), "recyclarr"
    )


def config_path() -> str:
    return os.path.join(app_data(), "recyclarr.yml")


def recyclarr_bin() -> str:
    override = env("POMPEY_RECYCLARR")
    if override:
        return override
    root = os.path.join(env("POMPEY_ENGINES", "/data/engines"), "recyclarr")
    nested = os.path.join(root, "recyclarr")
    if os.path.isfile(nested) and os.access(nested, os.X_OK):
        return nested
    return root


def dotnet_root() -> str:
    override = env("POMPEY_DOTNET_ROOT")
    if override:
        return override
    return os.path.join(env("POMPEY_ENGINES", "/data/engines"), "dotnet")


def apply_dotnet_env(child_env: dict) -> None:
    """Musl Recyclarr is a .NET apphost; glibc tarballs ship the runtime beside it."""
    root = dotnet_root()
    launcher = os.path.join(root, "dotnet")
    if not os.path.isfile(launcher):
        return
    child_env["DOTNET_ROOT"] = root
    child_env["DOTNET_ROOT_X64"] = root
    child_env["DOTNET_ROOT_ARM64"] = root


def load_secrets() -> dict:
    with open(secrets_path(), encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, dict):
        raise RuntimeError("secrets.json is not an object")
    return data


def yaml_quote(value: str) -> str:
    return json.dumps(str(value), ensure_ascii=False)


